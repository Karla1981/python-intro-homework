# create a hardcoded list of 8 nums

numbers = [1,2,3,4,5,6,7,8]

# print the first item
print(f"First item in NUMBERS list is: {numbers[0]}")

# print the last item - use a negative index 
print(f"Last item in NUMBERS list is: {numbers[-1]}")

# print - slice containing only the middle 4 items
print(f"the 4 middle nums of NUMBERS list are: {numbers[2:-2]}")

# print the full list in reverse order
print(f"The list in reverse order for NUMBERS list: {numbers[::-1]}")
